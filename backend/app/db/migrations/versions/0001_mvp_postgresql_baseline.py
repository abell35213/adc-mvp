def _type(spec):
    kind = spec[0]
    if kind == "enum":
        return postgresql.ENUM(*ENUMS[spec[1]], name=spec[1], create_type=False)
    if kind == "jsonb":
        return postgresql.JSONB()
    if kind == "uuid":
        return postgresql.UUID(as_uuid=True)
    if kind == "text":
        return sa.Text()
    if kind == "bool":
        return sa.Boolean()
    if kind == "int":
        return sa.Integer()
    if kind == "bigint":
        return sa.BigInteger()
    if kind == "dt":
        return postgresql.TIMESTAMP(timezone=spec[1])
    if kind == "str":
        return sa.String(length=spec[1])
    if kind == "date":
        return sa.Date()
    if kind == "float":
        return sa.Float()
    raise ValueError(f"Unsupported type spec: {spec!r}")


def _column(column):
    kwargs = {"nullable": column["nullable"]}
    server_default = column["server_default"]
    if server_default is not None:
        default_value = server_default
        column_kind = column["type"][0]
        if column_kind in {"enum", "text", "str"} and server_default.isidentifier():
            default_value = f"'{server_default}'"
        kwargs["server_default"] = sa.text(default_value)
    return sa.Column(column["name"], _type(column["type"]), **kwargs)


